-- ---------------------------------------------------------------------------
-- 关闭「访问IP校验」(verify_ip)
--
--   为什么内网部署要关：该检查的判据是 ipaddress.is_global()，只有公网地址才算
--   「真实 IP」。纯内网部署（以及任何经 Docker 端口映射访问的场景）来源必然是
--   回环 / 内网地址，这个校验永远不可能通过 → 每次登录都弹
--   「安全警告：未能获取到访问者的真实IP」。官方对纯内网部署的建议就是关掉它。
--
--   注意：verify_ip 只控制这个弹窗，**不参与任何鉴权逻辑**，关掉不等于降安全。
--   自己判断：需要的话把下面的语句删掉，或登录后在「系统设置」里改回来。
-- ---------------------------------------------------------------------------
INSERT INTO `settings` (`key`, `value`) VALUES ('verify_ip', 'false')
ON DUPLICATE KEY UPDATE `value` = 'false';

-- ---------------------------------------------------------------------------
-- 「登录IP绑定」(bind_ip) **保持默认开启**，不要在这里关闭。
--   它才是真正的鉴权开关：开启后 token 与首次登录的 IP 绑定，换 IP 需要重新登录。
-- ---------------------------------------------------------------------------

SELECT `key` AS `键`, `value` AS `值` FROM `settings` WHERE `key` IN ('verify_ip', 'bind_ip');
