#!/usr/bin/env bash
# ============================================================
# Evermodel Ops 状态总览
# ============================================================
set -euo pipefail

DEPLOY_DIR=$(cd "$(dirname "$0")" && pwd)

echo "==============================================="
echo "  中间件（Docker）"
echo "==============================================="
bash "$DEPLOY_DIR/middleware/status.sh" || true

echo
echo "==============================================="
echo "  后端 5 个进程（supervisor）"
echo "==============================================="
bash "$DEPLOY_DIR/backend/status.sh" || true

echo
echo "==============================================="
echo "  端口监听"
echo "==============================================="
ss -lntp 2>/dev/null | grep -E ':(80|9001|9002|3306|6379)\b' || echo "（无监听）"

echo
echo "==============================================="
echo "  前端可达性"
echo "==============================================="
code=$(curl -s -o /dev/null -w '%{http_code}' http://127.0.0.1/ || echo "000")
echo "GET http://127.0.0.1/ → HTTP $code"
